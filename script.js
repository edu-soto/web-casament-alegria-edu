let currentLang = 'ca';

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;

  // Update button active styles
  const btnCa = document.getElementById('lang-ca');
  const btnEs = document.getElementById('lang-es');

  if (lang === 'ca') {
    btnCa.className = "px-3 py-1 rounded-full transition-all duration-200 bg-brand-sage text-white shadow-sm";
    btnEs.className = "px-3 py-1 rounded-full transition-all duration-200 text-brand-muted hover:text-brand-charcoal";
  } else {
    btnEs.className = "px-3 py-1 rounded-full transition-all duration-200 bg-brand-sage text-white shadow-sm";
    btnCa.className = "px-3 py-1 rounded-full transition-all duration-200 text-brand-muted hover:text-brand-charcoal";
  }

  // Update Page Title
  if (translations[lang]?.pageTitle) {
    document.title = translations[lang].pageTitle;
  }

  // Update all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  try {
    localStorage.setItem('wedding_lang', lang);
  } catch (e) {
    // LocalStorage might be disabled in private mode
  }
}

