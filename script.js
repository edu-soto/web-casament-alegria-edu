// Countdown Timer logic to January 30, 2027, 12:00:00 CET
const weddingDate = new Date(2027, 0, 30, 12, 0, 0).getTime();

function updateCountdown() {
  const now = new Date().getTime();
  const distance = weddingDate - now;

  if (distance < 0) {
    document.getElementById('days').textContent = '0';
    document.getElementById('hours').textContent = '0';
    document.getElementById('minutes').textContent = '0';
    document.getElementById('seconds').textContent = '0';
    return;
  }

  const days = Math.floor(distance / (1000 * 60 * 60 * 24));
  const hours = Math.floor((distance % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
  const minutes = Math.floor((distance % (1000 * 60 * 60)) / (1000 * 60));
  const seconds = Math.floor((distance % (1000 * 60)) / 1000);

  const dEl = document.getElementById('days');
  const hEl = document.getElementById('hours');
  const mEl = document.getElementById('minutes');
  const sEl = document.getElementById('seconds');

  if (dEl) dEl.textContent = days;
  if (hEl) hEl.textContent = hours.toString().padStart(2, '0');
  if (mEl) mEl.textContent = minutes.toString().padStart(2, '0');
  if (sEl) sEl.textContent = seconds.toString().padStart(2, '0');
}

// Download .ics Calendar File
function downloadCalendarEvent() {
  const isCa = currentLang === 'ca';
  const title = isCa ? "Casament Alegria & Edu" : "Boda Alegria & Edu";
  const description = isCa 
    ? "12:00 Cerimònia a l'Església de Pompeia (Barcelona)\\n15:00 Aperitiu i Banquet a Masia Ca n'Illa (La Garriga)"
    : "12:00 Ceremonia en la Iglesia de Pompeia (Barcelona)\\n15:00 Aperitivo y Banquete en Masia Ca n'Illa (La Garriga)";
  const location = "Av. Diagonal, 450, Barcelona / Masia Ca n'Illa, La Garriga";

  const icsContent = 
`BEGIN:VCALENDAR
VERSION:2.0
PRODID:-//Casament Web//CA_ES
CALSCALE:GREGORIAN
METHOD:PUBLISH
BEGIN:VEVENT
SUMMARY:${title}
DESCRIPTION:${description}
LOCATION:${location}
DTSTART:20270130T110000Z
DTEND:20270131T030000Z
STATUS:CONFIRMED
BEGIN:VALARM
TRIGGER:-P1W
ACTION:DISPLAY
DESCRIPTION:Recordatori: Casament la setmana que ve!
END:VALARM
END:VEVENT
END:VCALENDAR`;

  const blob = new Blob([icsContent], { type: 'text/calendar;charset=utf-8' });
  const link = document.createElement('a');
  link.href = window.URL.createObjectURL(blob);
  link.setAttribute('download', 'casament-30-gener-2027.ics');
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

// Copy IBAN function with visual feedback
function copyIBAN() {
  const iban = "ES3201829003910207377004";
  const btnText = document.getElementById('copy-text');
  const isCa = currentLang === 'ca';
  
  const showSuccess = () => {
    if (btnText) {
      btnText.textContent = isCa ? "Copiat! ✓" : "¡Copiado! ✓";
      setTimeout(() => {
        btnText.textContent = isCa ? translations.ca["gifts.copy_btn"] : translations.es["gifts.copy_btn"];
      }, 2500);
    }
  };

  if (navigator.clipboard && navigator.clipboard.writeText) {
    navigator.clipboard.writeText(iban).then(showSuccess).catch(() => {
      fallbackCopy(iban, showSuccess);
    });
  } else {
    fallbackCopy(iban, showSuccess);
  }
}

function fallbackCopy(text, callback) {
  const textarea = document.createElement("textarea");
  textarea.value = text;
  textarea.style.position = "fixed";
  textarea.style.opacity = "0";
  document.body.appendChild(textarea);
  textarea.select();
  try {
    document.execCommand("copy");
    callback();
  } catch (err) {
    console.error("Copy failed", err);
  }
  document.body.removeChild(textarea);
}

// Initializer
document.addEventListener('DOMContentLoaded', () => {
  // Check saved language or browser language
  let savedLang = 'ca';
  try {
    savedLang = localStorage.getItem('wedding_lang') || 'ca';
  } catch (e) {
    savedLang = 'ca';
  }

  setLanguage(savedLang);
  updateCountdown();
  setInterval(updateCountdown, 1000);
});
